create table if not exists public.visitor_accounts (
  id bigint generated by default as identity primary key,
  display_name text not null check (char_length(display_name) between 1 and 80),
  email text not null unique,
  password_salt text not null,
  password_hash text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_accounts (
  id bigint generated by default as identity primary key,
  username text not null unique,
  display_name text not null check (char_length(display_name) between 1 and 80),
  email text not null unique,
  phone text not null,
  password_salt text not null,
  password_hash text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.visitor_sessions (
  token_hash text primary key,
  visitor_id bigint not null references public.visitor_accounts(id) on delete cascade,
  csrf_token text not null,
  expires_at timestamptz not null
);

create table if not exists public.admin_sessions (
  token_hash text primary key,
  admin_id bigint not null references public.admin_accounts(id) on delete cascade,
  csrf_token text not null,
  expires_at timestamptz not null
);

create index if not exists visitor_sessions_expiry on public.visitor_sessions (expires_at);
create index if not exists admin_sessions_expiry on public.admin_sessions (expires_at);

alter table public.visitor_accounts enable row level security;
alter table public.admin_accounts enable row level security;
alter table public.visitor_sessions enable row level security;
alter table public.admin_sessions enable row level security;

revoke all on public.visitor_accounts from anon, authenticated;
revoke all on public.admin_accounts from anon, authenticated;
revoke all on public.visitor_sessions from anon, authenticated;
revoke all on public.admin_sessions from anon, authenticated;

grant select, insert on public.visitor_accounts, public.admin_accounts to service_role;
grant select, insert, delete on public.visitor_sessions, public.admin_sessions to service_role;
grant usage, select on sequence public.visitor_accounts_id_seq, public.admin_accounts_id_seq to service_role;

create or replace function public.create_initial_admin(
  p_username text,
  p_display_name text,
  p_email text,
  p_phone text,
  p_password_salt text,
  p_password_hash text
)
returns table (id bigint, username text, display_name text, email text, phone text)
language plpgsql
security definer
set search_path = ''
as $$
begin
  lock table public.admin_accounts in exclusive mode;

  if exists (select 1 from public.admin_accounts) then
    raise exception 'Initial admin setup is already complete.' using errcode = 'P0001';
  end if;

  return query
  insert into public.admin_accounts (
    username, display_name, email, phone, password_salt, password_hash
  )
  values (
    lower(p_username), p_display_name, lower(p_email), p_phone, p_password_salt, p_password_hash
  )
  returning admin_accounts.id, admin_accounts.username, admin_accounts.display_name,
    admin_accounts.email, admin_accounts.phone;
end;
$$;

revoke all on function public.create_initial_admin(text, text, text, text, text, text) from public, anon, authenticated;
grant execute on function public.create_initial_admin(text, text, text, text, text, text) to service_role;
